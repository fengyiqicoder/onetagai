// static-llms-txt: write llms.txt and llms-full.txt for a static site from the HTML it already built.
// It reads a folder of .html files, keeps the main content of every page as Markdown, and writes
//   llms.txt       an index: one link per page (https://llmstxt.org)
//   llms-full.txt  every page in one file, one "# Title" + "Source: URL" block per page
// No network, no API key. The optional Ask AI part (askAi / inject) only adds a script tag.
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const { parse } = require("node-html-parser");

const MARK = "<!-- generated by static-llms-txt -->";
const SCRIPT = "https://onetagai.com/ask-docs.js";
const DROP = "script,style,noscript,template,svg,canvas,iframe,object,embed,nav,footer,aside,form,button,select,dialog,[hidden],[aria-hidden=true],.sr-only,.visually-hidden";
const ROOTS = ["main", "[role=main]", "article", "#content", ".content", "body"];
const BLOCK = new Set(["p", "div", "section", "article", "main", "header", "figure", "figcaption", "details", "summary", "address", "dd", "dt", "dl", "tr", "table", "thead", "tbody", "tfoot", "ul", "ol", "li", "blockquote", "pre", "h1", "h2", "h3", "h4", "h5", "h6", "hr", "br"]);

function decode(text) {
  return String(text)
    .replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"').replace(/&#0?39;|&apos;/g, "'")
    .replace(/&#(\d+);/g, (m, n) => safeChar(Number(n), m)).replace(/&#x([0-9a-f]+);/gi, (m, n) => safeChar(parseInt(n, 16), m));
}
function safeChar(code, fallback) {
  try { return String.fromCodePoint(code); } catch (e) { return fallback; }
}
const squash = (s) => decode(s).replace(/\s+/g, " ");
const tagOf = (node) => (node.rawTagName || "").toLowerCase();

function touchingLinks(node) {
  const prev = node.previousSibling;
  return !!prev && prev.nodeType === 1 && tagOf(node) === "a" && tagOf(prev) === "a";
}

// Inline text of a node: links and emphasis become their text, <code> keeps backticks.
function inline(node) {
  if (node.nodeType === 3) return squash(node.rawText);
  if (node.nodeType !== 1) return "";
  const tag = tagOf(node);
  if (tag === "br") return "\n";
  if (tag === "img") return "";
  // Block children (a heading inside a list item) and back-to-back links get a space, so words do not run together.
  let inner = "";
  for (const c of node.childNodes) {
    const t = c.nodeType === 1 ? tagOf(c) : "";
    const spaced = t && (BLOCK.has(t) || touchingLinks(c));
    inner += (spaced ? " " : "") + inline(c) + (t && BLOCK.has(t) && t !== "br" ? " " : "");
  }
  if (tag === "code" && inner.trim()) return "`" + inner.trim() + "`";
  return inner;
}

function codeBlock(node) {
  const code = node.querySelector("code") || node;
  const wrap = node.parentNode && node.parentNode.getAttribute ? node.parentNode.getAttribute("class") || "" : "";  // VitePress: <div class="language-js"><pre>
  const cls = (code.getAttribute("class") || "") + " " + (node.getAttribute("class") || "") + " " + wrap + " " + (node.getAttribute("data-language") || node.getAttribute("data-lang") || "");
  const lang = (/(?:language|lang|highlight-source)-([\w+#.-]+)/.exec(cls) || [])[1] || (node.getAttribute("data-language") || node.getAttribute("data-lang") || "");
  // Line-per-element highlighters (Shiki, Expressive Code) put each line in its own block element.
  const lines = code.querySelectorAll(".line, .ec-line");
  const text = lines.length > 1 ? lines.map((l) => decode(l.text)).join("\n") : decode(code.text);
  const body = text.replace(/\s+$/, "").replace(/^\n+/, "");
  if (!body.trim()) return "";
  const fence = body.includes("```") ? "~~~~" : "```";
  return fence + lang + "\n" + body + "\n" + fence;
}

function table(node) {
  const rows = node.querySelectorAll("tr").map((tr) => tr.querySelectorAll("th,td").map((c) => inline(c).replace(/\s+/g, " ").replace(/\|/g, "\\|").trim()));
  const filled = rows.filter((r) => r.length);
  if (!filled.length) return "";
  const out = ["| " + filled[0].join(" | ") + " |", "| " + filled[0].map(() => "---").join(" | ") + " |"];
  for (const r of filled.slice(1)) out.push("| " + r.join(" | ") + " |");
  return out.join("\n");
}

function list(node, depth) {
  const ordered = tagOf(node) === "ol";
  const out = [];
  let n = 0;
  for (const li of node.childNodes) {
    if (li.nodeType !== 1 || tagOf(li) !== "li") continue;
    n++;
    const own = [], nested = [];
    for (const c of li.childNodes) {
      const t = c.nodeType === 1 ? tagOf(c) : "";
      if (t === "ul" || t === "ol") nested.push(list(c, depth + 1));
      else if (t === "pre") nested.push(codeBlock(c).replace(/^/gm, "  ".repeat(depth + 1)));
      else own.push(t && BLOCK.has(t) ? " " + inline(c) + " " : (t && touchingLinks(c) ? " " : "") + inline(c));
    }
    const text = own.join("").replace(/\s+/g, " ").trim();
    if (text) out.push("  ".repeat(depth) + (ordered ? n + ". " : "- ") + text);
    for (const x of nested) if (x) out.push(x);
  }
  return out.join("\n");
}

// Markdown blocks of a content root. `shift` moves page headings down so a page's own
// sections sit under its "# Title" in llms-full.txt (h2 → ##, h3 → ###, …).
function blocks(root, ctx) {
  const out = [];
  let run = [];
  const flush = () => {
    const text = run.join("").replace(/[ \t]*\n[ \t]*/g, "\n").replace(/[ \t]+/g, " ").trim();
    if (text) out.push(text);
    run = [];
  };
  const walk = (node) => {
    if (node.nodeType === 3) { run.push(squash(node.rawText)); return; }
    if (node.nodeType !== 1) return;
    const tag = tagOf(node);
    if (!BLOCK.has(tag)) {
      if (node.childNodes.some((c) => c.nodeType === 1 && BLOCK.has(tagOf(c)))) { node.childNodes.forEach(walk); return; }
      run.push((touchingLinks(node) ? " " : "") + inline(node));
      return;
    }
    if (tag === "br") { run.push("\n"); return; }
    flush();
    if (/^h[1-6]$/.test(tag)) {
      const text = inline(node).replace(/\s+/g, " ").replace(/^#+\s*|\s*[#¶🔗]+$/g, "").trim();
      if (!text) return;
      const level = Number(tag[1]);
      if (level === 1 && !ctx.h1) { ctx.h1 = text; return; }   // the page title, written once by the caller
      const id = node.getAttribute("id") || (node.querySelector("[id]") || { getAttribute: () => "" }).getAttribute("id") || "";
      out.push({ heading: Math.max(2, level), text, id });
      return;
    }
    if (tag === "pre") { const b = codeBlock(node); if (b) out.push(b); return; }
    if (tag === "ul" || tag === "ol") { const b = list(node, 0); if (b) out.push(b); return; }
    if (tag === "table") { const b = table(node); if (b) out.push(b); return; }
    if (tag === "hr") return;
    if (tag === "blockquote") {
      const inner = blocks(node, ctx).filter((b) => typeof b === "string").join("\n\n");
      if (inner) out.push(inner.replace(/^/gm, "> "));
      return;
    }
    node.childNodes.forEach(walk);
    flush();
  };
  root.childNodes.forEach(walk);
  flush();
  return out;
}

function meta(doc, selector) {
  const el = doc.querySelector(selector);
  return el ? decode(el.getAttribute("content") || "").replace(/\s+/g, " ").trim() : "";
}

// One HTML document → { title, description, canonical, noindex, redirect, sections, text }.
// sections: [{ heading, id, text }] where the first one (heading "") is the text before any h2.
// Minifiers such as html-minifier-terser (removeOptionalTags, used by Docusaurus) drop the table end
// tags HTML lets you omit. node-html-parser copes with omitted </li> and </p> but not with table parts:
// one such table and <body> and <main> vanish from the tree. Put the table end tags back first.
// Well-formed tables come out unchanged; nested tables are left alone.
function closeTableTags(html) {
  if (!/<table\b/i.test(html)) return html;
  return html.replace(/<table\b[\s\S]*?<\/table>/gi, (table) => {
    if (/<table\b/i.test(table.slice(6))) return table;
    let cell = "", row = false, part = "", out = "", last = 0, m;
    const re = /<(\/?)(td|th|tr|thead|tbody|tfoot|table)\b[^>]*>/gi;
    const shut = (to) => {
      let s = "";
      if (cell) { s += "</" + cell + ">"; cell = ""; }
      if (to !== "cell" && row) { s += "</tr>"; row = false; }
      if (to === "part" && part) { s += "</" + part + ">"; part = ""; }
      return s;
    };
    while ((m = re.exec(table))) {
      out += table.slice(last, m.index);
      last = re.lastIndex;
      const end = m[1] === "/", tag = m[2].toLowerCase();
      if (end) {
        if (tag === "td" || tag === "th") { if (cell) { out += m[0]; cell = ""; } }
        else if (tag === "tr") { out += shut("row").replace(/<\/tr>$/, "") + m[0]; row = false; }
        else if (tag === "table") out += shut("part") + m[0];
        else { out += shut("row") + m[0]; part = ""; }
      } else if (tag === "td" || tag === "th") { out += shut("cell") + m[0]; cell = tag; }
      else if (tag === "tr") { out += shut("row") + m[0]; row = true; }
      else if (tag === "table") out += m[0];
      else { out += shut("part") + m[0]; part = tag; }
    }
    return out + table.slice(last);
  });
}

function readHtml(html, options) {
  const o = options || {};
  const doc = parse(closeTableTags(String(html)), { comment: false, blockTextElements: { script: false, style: false, noscript: false } });
  const robots = meta(doc, 'meta[name="robots"]') + " " + meta(doc, 'meta[name="googlebot"]');
  const refresh = doc.querySelector('meta[http-equiv="refresh"], meta[http-equiv="Refresh"]');
  const canonicalEl = doc.querySelector('link[rel="canonical"]');
  const titleEl = doc.querySelector("title");
  const docTitle = titleEl ? decode(titleEl.text).replace(/\s+/g, " ").trim() : "";
  const info = {
    title: "", docTitle,
    siteName: meta(doc, 'meta[property="og:site_name"]'),
    description: meta(doc, 'meta[name="description"]') || meta(doc, 'meta[property="og:description"]'),
    canonical: (canonicalEl && canonicalEl.getAttribute("href")) || meta(doc, 'meta[property="og:url"]') || "",
    noindex: /noindex/i.test(robots),
    redirect: !!refresh,
    lang: (doc.querySelector("html") && doc.querySelector("html").getAttribute("lang")) || "",
    sections: [], text: "",
  };
  const selectors = [].concat(o.content || []).filter(Boolean).concat(ROOTS);
  let root = null;
  for (const s of selectors) { try { root = doc.querySelector(s); } catch (e) { root = null; } if (root) break; }
  if (!root) return info;
  for (const s of [DROP].concat(o.exclude || [])) {
    let found = [];
    try { found = root.querySelectorAll(s); } catch (e) { /* a selector the parser cannot read is skipped */ }
    for (const el of found) el.remove();
  }
  const ctx = { h1: "" };
  const parts = blocks(root, ctx);
  let cur = { heading: "", level: 0, id: "", lines: [] };
  const sections = [cur];
  for (const b of parts) {
    if (typeof b === "string") { cur.lines.push(b); continue; }
    if (b.heading === 2) { cur = { heading: b.text, level: 2, id: b.id, lines: [] }; sections.push(cur); }
    else cur.lines.push("#".repeat(b.heading) + " " + b.text);
  }
  info.sections = sections.map((s) => ({ heading: s.heading, id: s.id, text: s.lines.join("\n\n").trim() })).filter((s) => s.heading || s.text);
  info.text = info.sections.map((s) => (s.heading ? "## " + s.heading + "\n\n" : "") + s.text).join("\n\n").trim();
  info.title = ctx.h1 || meta(doc, 'meta[property="og:title"]') || docTitle;
  return info;
}

// "a/**/b*.html" → RegExp, matched against paths relative to the site folder with "/" separators.
function globToRegExp(glob) {
  const g = String(glob).replace(/^\.?\//, "");
  let re = "";
  for (let i = 0; i < g.length; i++) {
    const c = g[i];
    if (c === "*") {
      if (g[i + 1] === "*") { re += ".*"; i++; if (g[i + 1] === "/") i++; }
      else re += "[^/]*";
    } else if (c === "?") re += "[^/]";
    else re += c.replace(/[.+^${}()|[\]\\]/g, "\\$&");
  }
  return new RegExp("^" + re + "$");
}

function walkHtml(dir) {
  const out = [];
  const visit = (abs, rel) => {
    for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
      if (entry.name.startsWith(".") || entry.name === "node_modules") continue;
      const childAbs = path.join(abs, entry.name), childRel = rel ? rel + "/" + entry.name : entry.name;
      if (entry.isDirectory()) visit(childAbs, childRel);
      else if (/\.html?$/i.test(entry.name)) out.push(childRel);
    }
  };
  visit(dir, "");
  return out;
}

function urlPath(rel, cleanUrls) {
  let p = "/" + rel;
  if (/(^|\/)index\.html?$/i.test(rel)) p = p.replace(/index\.html?$/i, "");
  else if (cleanUrls) p = p.replace(/\.html?$/i, "");
  return p.split("/").map((seg) => encodeURIComponent(seg).replace(/%2B/g, "+")).join("/");
}

function joinUrl(site, p) {
  if (!site) return "";
  return String(site).replace(/\/+$/, "") + (p.startsWith("/") ? p : "/" + p);
}

// Home page first, then by depth, then by path: the order pages appear in both files.
function byPath(a, b) {
  const da = a.path.split("/").filter(Boolean).length, db = b.path.split("/").filter(Boolean).length;
  return da - db || (a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
}

// Read every page of a built site. Returns [{ file, path, url, title, description, sections, text }].
function scan(dir, options) {
  const o = options || {};
  const root = path.resolve(dir);
  if (!fs.existsSync(root) || !fs.statSync(root).isDirectory()) throw new Error("static-llms-txt: " + root + " is not a folder. Pass the folder your site was built into.");
  const excludes = [].concat(o.exclude || []).map(globToRegExp);
  const pages = [];
  for (const rel of walkHtml(root)) {
    if (/(^|\/)(404|500)(\.html?|\/index\.html?)$/i.test(rel)) continue;
    if (excludes.some((re) => re.test(rel))) continue;
    const html = fs.readFileSync(path.join(root, rel), "utf8");
    const info = readHtml(html, { content: o.content, exclude: o.remove });
    if (info.noindex || info.redirect) continue;
    if (!info.text && html.length > 2000 && o.warn !== false) {
      console.warn("static-llms-txt: found no text in " + rel + ", so it is left out. If the page has text, please report it at https://github.com/fengyiqicoder/onetagai/issues");
    }
    if (info.text.length < (o.minLength === undefined ? 40 : o.minLength)) continue;
    const p = urlPath(rel, o.cleanUrls);
    const url = o.site ? joinUrl(o.site, p) : /^https?:\/\//i.test(info.canonical) ? info.canonical : "";
    pages.push({ file: rel, path: p, url, title: info.title || p, docTitle: info.docTitle, siteName: info.siteName, description: info.description, sections: info.sections, text: info.text });
  }
  return pages.sort(byPath);
}

const oneLine = (s) => String(s || "").replace(/\s+/g, " ").trim();

// pages: [{ url, path?, title, description?, text? | sections? | html? }] → { llms, llmsFull }.
function build(pages, options) {
  const o = options || {};
  const list = pages.map((p) => {
    if (p.html && !p.text && !p.sections) {
      const info = readHtml(p.html, { content: o.content, exclude: o.remove });
      return Object.assign({}, p, { title: p.title || info.title, description: p.description || info.description, sections: info.sections, text: info.text });
    }
    return p;
  }).filter((p) => p && (p.text || (p.sections && p.sections.length)));
  const home = list.find((p) => (p.path || "") === "/") || list[0] || {};
  const title = oneLine(o.title || home.siteName || (home.docTitle || home.title || "").split(/\s+[|·–—-]\s+/).pop() || "Site");
  const description = oneLine(o.description || home.description || "");
  const link = (p) => p.url || (o.site ? joinUrl(o.site, p.path || "/") : p.path || "");

  const index = ["# " + title, ""];
  if (description) index.push("> " + description, "");
  index.push("## " + (o.section || "Pages"), "");
  for (const p of list) {
    const d = oneLine(p.description);
    index.push("- [" + oneLine(p.title).replace(/[[\]]/g, "") + "](" + link(p) + ")" + (d ? ": " + d : ""));
  }
  if (o.full !== false) index.push("", "## Optional", "", "- [Full text of every page](" + (o.site ? joinUrl(o.site, "/llms-full.txt") : "/llms-full.txt") + ")");
  index.push("", MARK, "");

  const full = [];
  for (const p of list) {
    const url = link(p);
    const abs = /^https?:\/\//i.test(url);
    full.push("# " + oneLine(p.title), "");
    if (abs) full.push("Source: " + url, "");
    const sections = p.sections || [{ heading: "", id: "", text: p.text }];
    for (const s of sections) {
      if (s.heading) {
        full.push("## " + oneLine(s.heading), "");
        if (abs && s.id) full.push("Source: " + url.replace(/#.*$/, "") + "#" + encodeURIComponent(s.id), "");
      }
      if (s.text) full.push(s.text, "");
    }
  }
  full.push(MARK, "");
  return { title, description, pages: list, llms: index.join("\n"), llmsFull: full.join("\n").replace(/\n{3,}/g, "\n\n") };
}

// A file we did not write (another plugin's llms.txt, or one written by hand) is left alone.
function writeOwn(file, text, force) {
  if (!force && fs.existsSync(file) && !fs.readFileSync(file, "utf8").includes(MARK)) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  return true;
}

// Scan a built site and write llms.txt and llms-full.txt into it.
function generate(dir, options) {
  const o = options || {};
  const pages = o.pages || scan(dir, o);
  const result = build(pages, o);
  const out = path.resolve(o.out || dir);
  const written = [], skipped = [];
  const put = (name, text) => (o.write === false ? null : (writeOwn(path.join(out, name), text, o.force) ? written : skipped).push(name));
  put("llms.txt", result.llms);
  if (o.full !== false) put("llms-full.txt", result.llmsFull);
  return Object.assign(result, { written, skipped });
}

const attr = (v) => String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

// The Ask AI script tag. Options become data-* attributes; `ref` names the plugin that added it.
function scriptTag(options) {
  const o = options || {};
  const names = ["key", "ref", "label", "placeholder", "position", "button", "color", "theme", "lang", "rules", "index"];
  let tag = '<script async src="' + attr(o.src || SCRIPT) + '"';
  for (const n of names) if (o[n] !== undefined && o[n] !== null && o[n] !== "") tag += " data-" + n + '="' + attr(o[n]) + '"';
  return tag + "></script>";
}

// Add the Ask AI script tag before </body> of every page in a built site. Running it twice changes nothing.
function inject(dir, options) {
  const root = path.resolve(dir);
  const o = options || {};
  const excludes = [].concat(o.exclude || []).map(globToRegExp);
  const tag = scriptTag(o);
  const changed = [];
  for (const rel of walkHtml(root)) {
    if (excludes.some((re) => re.test(rel))) continue;
    const file = path.join(root, rel);
    const html = fs.readFileSync(file, "utf8");
    if (/<script[^>]+\/ask-docs\.js/i.test(html)) continue;
    const at = html.search(/<\/body\s*>(?![\s\S]*<\/body\s*>)/i);
    if (at === -1) continue;
    fs.writeFileSync(file, html.slice(0, at) + tag + "\n" + html.slice(at));
    changed.push(rel);
  }
  return changed;
}

module.exports = { generate, scan, build, readHtml, inject, scriptTag, globToRegExp, MARK, SCRIPT };
